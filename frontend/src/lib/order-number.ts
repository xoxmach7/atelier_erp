/**
 * Короткий вид номера заказа для списков и заголовков.
 *
 * Автонумерация даёт «О-2026-933» — в таблице это занимает половину колонки и
 * читается плохо: год и префикс одинаковы у всех заказов, различает их только
 * хвост. Показываем «№933».
 *
 * Владелец может задать свой номер при создании заказа. Такой номер трогать
 * нельзя — он показывается как есть, иначе «ЗАКАЗ-А1» превратился бы в «№1».
 */

/** Автоформат нумератора: префикс-год-номер, например О-2026-933. */
const AUTO_NUMBER = /^[^\s-]+-\d{4}-(\d+)$/;

export function shortOrderNumber(orderNumber?: string | null): string {
  if (!orderNumber) return "";
  const match = orderNumber.match(AUTO_NUMBER);
  return match ? `№${match[1]}` : orderNumber;
}
